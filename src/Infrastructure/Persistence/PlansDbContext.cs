using Microsoft.EntityFrameworkCore;

namespace Snail.MCP.Plans.Infrastructure.Persistence;

/// <summary>Table row of a plan.</summary>
public sealed class PlanRow
{
    /// <summary>Identity of the plan.</summary>
    public Guid Id { get; set; }

    /// <summary>Agent owning the plan.</summary>
    public string AgentId { get; set; } = "";

    /// <summary>Project the plan belongs to.</summary>
    public string ProjectName { get; set; } = "";

    /// <summary>The immutable goal.</summary>
    public string Objective { get; set; } = "";

    /// <summary>Where the work stands.</summary>
    public string Summary { get; set; } = "";

    /// <summary>Name of a <see cref="Core.PlanStatus"/> value, stored as text so the file stays readable.</summary>
    public string Status { get; set; } = "";

    /// <summary>Concurrency token: a write states the version it read.</summary>
    public int Version { get; set; }

    /// <summary>Unix milliseconds of drafting.</summary>
    public long Created { get; set; }

    /// <summary>Unix milliseconds of the last write.</summary>
    public long Updated { get; set; }

    /// <summary>Unix milliseconds of leaving the active status.</summary>
    public long? Completed { get; set; }

    /// <summary>The steps of this plan.</summary>
    public List<StepRow> Steps { get; set; } = [];
}

/// <summary>Table row of a step.</summary>
public sealed class StepRow
{
    /// <summary>Identity of the step.</summary>
    public Guid Id { get; set; }

    /// <summary>Plan the step belongs to.</summary>
    public Guid PlanId { get; set; }

    /// <summary>Position inside the plan.</summary>
    public int OrderIndex { get; set; }

    /// <summary>What is to be done.</summary>
    public string Title { get; set; } = "";

    /// <summary>Name of a <see cref="Core.StepStatus"/> value, stored as text so the file stays readable.</summary>
    public string Status { get; set; } = "";

    /// <summary>Latest note on the step.</summary>
    public string Note { get; set; } = "";

    /// <summary>How many times the step was started.</summary>
    public int Attempts { get; set; }

    /// <summary>Unix milliseconds of the first start.</summary>
    public long? Started { get; set; }

    /// <summary>Unix milliseconds of reaching a terminal status.</summary>
    public long? Completed { get; set; }

    /// <summary>The owning plan.</summary>
    public PlanRow? Plan { get; set; }
}

/// <summary>The relational schema of the plans database.</summary>
/// <remarks>
/// Two invariants are held by partial unique indexes rather than by code: one step of a plan in progress,
/// and one active plan per agent and project. A check in the application would be a race between two
/// sessions writing the same file; a constraint is not.
/// <para>
/// Identities are declared as never generated by the database because the domain mints them. Left as
/// generated, a step added to a plan already tracked is taken for an existing row and written as an
/// update that matches nothing, and the revision fails as a concurrency conflict.
/// </para>
/// </remarks>
public sealed class PlansDbContext(DbContextOptions<PlansDbContext> options) : DbContext(options)
{
    /// <summary>The stored plans.</summary>
    public DbSet<PlanRow> Plans => Set<PlanRow>();

    /// <summary>The stored steps.</summary>
    public DbSet<StepRow> Steps => Set<StepRow>();

    /// <inheritdoc />
    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        var plans = modelBuilder.Entity<PlanRow>();

        plans.ToTable("Plans");
        plans.HasKey(row => row.Id);
        plans.Property(row => row.Id).ValueGeneratedNever();
        plans.Property(row => row.Version).IsConcurrencyToken();
        plans.HasIndex(row => new { row.AgentId, row.ProjectName, row.Status });
        plans.HasIndex(row => row.Status);

        plans.HasIndex(row => new { row.AgentId, row.ProjectName })
            .IsUnique()
            .HasFilter($"\"Status\" = '{nameof(Core.PlanStatus.Active)}'")
            .HasDatabaseName("UX_Plans_OneActivePerAgentAndProject");

        plans.HasMany(row => row.Steps)
            .WithOne(row => row.Plan!)
            .HasForeignKey(row => row.PlanId)
            .OnDelete(DeleteBehavior.Cascade);

        var steps = modelBuilder.Entity<StepRow>();

        steps.ToTable("Steps");
        steps.HasKey(row => row.Id);
        steps.Property(row => row.Id).ValueGeneratedNever();
        steps.HasIndex(row => new { row.PlanId, row.OrderIndex });

        steps.HasIndex(row => row.PlanId)
            .IsUnique()
            .HasFilter($"\"Status\" = '{nameof(Core.StepStatus.InProgress)}'")
            .HasDatabaseName("UX_Steps_OneInProgressPerPlan");
    }
}
